/** 整串匹配的规则，用来翻译「拼出来」的文案（周次、进度、各种 Snackbar）。 */
internal val EN_RULES: List<Rule> = listOf(
    Rule(Regex("""(\d{1,2})月""")) { "${MONTHS[it.groupValues[1].toInt().coerceIn(1, 12) - 1]}" },
    Rule(Regex("""第 (\d+) 周""")) { "Week ${it.groupValues[1]}" },
    Rule(Regex("""第 (\d+) 周课表""")) { "Week ${it.groupValues[1]} timetable" },
    Rule(Regex("""第 (\d+) 周没有课""")) { "No classes in week ${it.groupValues[1]}" },
    Rule(Regex("""本周 (\d+) 节课 · 全学期 (\d+) 门 · 共 (\d+) 周""")) {
        "${it.groupValues[1]} classes this week · ${it.groupValues[2]} courses · ${it.groupValues[3]} weeks"
    },
    Rule(Regex("""共 (\d+) 周""")) { "${it.groupValues[1]} weeks" },
    Rule(Regex("""共 (第\d+-\d+节)""")) { Lang.tr(it.groupValues[1]) },
    Rule(Regex("""把第 (\d+) 周设为当前周""")) { "Make week ${it.groupValues[1]} current" },
    Rule(Regex("""已将第 (\d+) 周设为当前周""")) { "Week ${it.groupValues[1]} is now the current week" },
    Rule(Regex("""当前周为第 (\d+) 周 · 共 (\d+) 周""")) {
        "Current week ${it.groupValues[1]} of ${it.groupValues[2]}"
    },
    Rule(Regex("""当前为第 (\d+) 周。选择后会把学期开始日期顺延，使所选周包含今天。""")) {
        "Today is in week ${it.groupValues[1]}. The semester start shifts so the picked week includes today."
    },
    Rule(Regex("""生成第 (\d+) 周的长图，可直接发微信 / QQ""")) {
        "Long image for week ${it.groupValues[1]}, ready for WeChat / QQ"
    },
